#!/usr/bin/env bun
/**
 * gen-tokens.ts — the only writer of `src/themes/blackboard.css`. Reads the palette (14 colours and
 * three ratios per block), expands it through `src/themes/derive.ts`, and writes the 29 roles
 * `src/themes/roles.ts` declares. Refuses to write anything the three do not agree on.
 *
 *   bun run theme:sync    write the file
 *   bun run theme:check   compare only; exit 1 when the file is stale
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { type Block, expand, validateBlock } from "../src/themes/derive";
import { DEFAULT_THEME, MODES, REQUIRED, THEMES } from "../src/themes/roles";

const PKG = join(dirname(fileURLToPath(import.meta.url)), "..");
const PALETTE = join(PKG, "..", "bb-tokens", "palette", "palette.json");
const OUT = join(PKG, "src", "themes", "blackboard.css");

type Palette = Record<string, Record<string, Record<string, string> | undefined>>;

/** Declared, not a const arrow: only a function declaration narrows control flow after the call. */
function fail(message: string): never {
  console.error("gen-tokens: " + message);
  process.exit(1);
}

const palette: Palette = JSON.parse(readFileSync(PALETTE, "utf8"));

if (THEMES.filter((t) => t.isDefault).length !== 1) fail("exactly one theme must be isDefault");

const lines: string[] = [
  "/*",
  " * GENERATED by scripts/gen-tokens.ts — do not edit.",
  " * Colours come from packages/bb-tokens/palette/palette.json, expanded by src/themes/derive.ts,",
  " * role names from src/themes/roles.ts. Change those and run `bun run theme:sync`.",
  " */",
];

for (const theme of THEMES) {
  const byMode = palette[theme.id];
  if (!byMode) fail("palette has no theme " + theme.id);
  for (const mode of MODES) {
    const block = byMode[mode] as Block | undefined;
    if (!block) fail("palette has no " + theme.id + "/" + mode);

    // The shape of a block is a gate, not a convention: a role kept by hand here is exactly what
    // the slim palette exists to prevent, and a ratio off the grid is a hex wearing a percentage.
    const problems = validateBlock(theme.id + "/" + mode, block);
    if (problems.length) fail(problems.join("\n  gen-tokens: "));

    const values = expand(block);

    // The default theme's light block also serves :root, so an unpicked browser still paints a
    // complete palette. Every other block is keyed by the two attributes.
    const selector =
      theme.id === DEFAULT_THEME && mode === "light"
        ? ':root, [data-theme="' + theme.id + '"][data-mode="light"]'
        : '[data-theme="' + theme.id + '"][data-mode="' + mode + '"]';
    lines.push("", selector + " {", "  color-scheme: " + mode + ";");
    for (const role of REQUIRED) lines.push("  --theme-" + role + ": " + values[role] + ";");
    lines.push("}");
  }
}

const css = lines.join("\n") + "\n";

if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== css) fail("theme files are out of date — run `bun run theme:sync`");
  console.log("theme files are up to date (" + THEMES.length + ")");
  process.exit(0);
}

writeFileSync(OUT, css);
console.log("wrote " + OUT);
