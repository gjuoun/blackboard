/**
 * Build `lib/db/migrations/bundled.ts` from drizzle-kit's output, so the runtime never reads the
 * migrations folder (Next standalone does not ship it). Run after `drizzle-kit generate`:
 *
 *   bun run db:generate
 *
 * What it emits, per migration file: tag, hash (sha256 of the sql), folderMillis (journal order
 * key), and the statements. The BASELINE file gets `IF NOT EXISTS` injected into its
 * CREATE TABLE / CREATE INDEX statements — that's what lets an already-existing database adopt
 * the baseline without failing; new migrations are emitted verbatim (they must run as written).
 * It also emits `BASELINE_COLUMNS` from the baseline snapshot: the column list the open-time
 * ALTER pass backfills for databases created before drizzle was wired in.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const DIR = new URL("../lib/db/migrations", import.meta.url).pathname;
const journal = JSON.parse(readFileSync(join(DIR, "meta/_journal.json"), "utf8")) as { entries: { tag: string; when: number }[] };

const files = journal.entries.map((e) => {
  const sql = readFileSync(join(DIR, `${e.tag}.sql`), "utf8");
  const stmts = sql
    .split("--> statement-breakpoint")
    .map((s) => s.trim())
    .filter(Boolean);
  return { tag: e.tag, folderMillis: e.when, hash: createHash("sha256").update(sql).digest("hex"), stmts };
});

const BASELINE = journal.entries[0]?.tag;
const baseline = files[0];
if (!baseline) throw new Error("no migrations generated");
if (baseline.tag !== BASELINE) throw new Error("baseline must be first");

baseline.stmts = baseline.stmts.map((s) =>
  s.replace(/^CREATE TABLE `/, "CREATE TABLE IF NOT EXISTS `").replace(/^CREATE INDEX `/, "CREATE INDEX IF NOT EXISTS `").replace(/^CREATE UNIQUE INDEX `/, "CREATE UNIQUE INDEX IF NOT EXISTS `"),
);

// Baseline columns for the ALTER-if-missing adoption pass.
const snap = JSON.parse(readFileSync(join(DIR, "meta/0000_snapshot.json"), "utf8")) as {
  tables: Record<string, { name: string; columns: Record<string, { name: string; type: string }> }>;
};
const baselineColumns: Record<string, { name: string; type: string }[]> = {};
for (const t of Object.values(snap.tables)) {
  baselineColumns[t.name] = Object.values(t.columns).map((c) => ({ name: c.name, type: c.type.toUpperCase() }));
}

const out = `// GENERATED by scripts/gen-migrations.ts — do not edit. Regenerate with: bun run db:generate
export type BundledMigration = { tag: string; folderMillis: number; hash: string; stmts: string[] };
export const MIGRATIONS: BundledMigration[] = ${JSON.stringify(files, null, 2)};
export const BASELINE_COLUMNS: Record<string, { name: string; type: string }[]> = ${JSON.stringify(baselineColumns, null, 2)};
export const BASELINE_TAG = ${JSON.stringify(baseline.tag)};
`;

writeFileSync(join(DIR, "bundled.ts"), out);
console.log(`wrote lib/db/migrations/bundled.ts (${files.length} migrations, baseline ${baseline.tag} made idempotent)`);
